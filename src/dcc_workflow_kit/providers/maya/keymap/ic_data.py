"""Industry Compatible keymap data as static data (``ic_<major>_<minor>.py``).

Generated by tools/gen_ic_data.py from Blender's own
``$S\\presets\\keyconfig\\keymap_data\\industry_compatible_data.py`` (``generate_keymaps(Params())``) — one file
per Blender minor whose data differs; the newest file not newer than the running Blender is used. The add-on never
executes Blender's preset file itself (store review, GitHub #40).
``patch.KeyconfigData.remove`` still raises (5.2 / 5.3) or records ``patch.DRIFT`` (5.0 / 5.1) when an item we patch is
missing. Blender 4.5's data file is gone (the kit needs 5.0+).
"""

import copy
import sys
from importlib import import_module

from .. import compat

# Minors with a data file (tools/gen_ic_data.py writes one only when the data changed).
VERSIONS = ((5, 0), (5, 1), (5, 2), (5, 3))


def data_version(version=None):
    version = tuple(version or compat.VERSION)
    found = [v for v in VERSIONS if v <= version]
    return found[-1] if found else VERSIONS[0]


def generate():
    """Return a new list of IC keyconfig data (safe to mutate), as the kit's patches expect it: Ctrl keys only. On
    macOS the Cmd copies are made after the patches (``for_platform``)."""
    v = data_version()
    return copy.deepcopy(import_module(f".ic_{v[0]}_{v[1]}", __package__).DATA)


def for_platform(data):
    """The patched keymap data for this platform: on macOS every Ctrl key also answers Cmd, the kit's own keys too
    (Blender's macOS rule, which leaves Cmd+H / M / W / Space / Tab and a few more to the system). Made after the
    patches, so a Ctrl key the kit removed or replaced leaves no Cmd copy behind (#432)."""
    if sys.platform == "darwin":
        from bl_keymap_utils.platform_helpers import keyconfig_data_oskey_from_ctrl_for_macos
        data = keyconfig_data_oskey_from_ctrl_for_macos(data)
    return data


def platform_tool(tool):
    """``tool`` (a kit ``WorkSpaceTool`` class) with its ``bl_keymap`` for this platform, given to
    ``bpy.utils.register_tool``: on macOS each Ctrl item of the tool also answers Cmd, like the kit's other keys."""
    items = tool.__dict__.get("_allset_keymap")
    if items is None:
        items = tool._allset_keymap = getattr(tool, "bl_keymap", None)     # its own or a base class's
    if isinstance(items, tuple) and all(isinstance(i, tuple) and len(i) == 3 for i in items):
        data = for_platform([("", {}, {"items": [i for i in items]})])
        # an item with "ctrl": False gets an "oskey": False copy, which is the same key: left out
        tool.bl_keymap = tuple(i for i in data[0][2]["items"] if i[1].get("oskey", True) is not False)
    return tool

"""Run with factory Blender 4.2.9 to snapshot its GPL Industry Compatible preset."""
import pprint
import runpy
from pathlib import Path
import bpy

assert bpy.app.version[:2] == (4, 2), bpy.app.version
source = Path(bpy.utils.system_resource('SCRIPTS')) / 'presets/keyconfig/keymap_data/industry_compatible_data.py'
module = runpy.run_path(str(source))
data = module['generate_keymaps'](module['Params']())
output = Path(__file__).resolve().parents[1] / 'src/dcc_workflow_kit/providers/maya/keymap/ic_4_2.py'
output.write_text('# SPDX-License-Identifier: GPL-2.0-or-later\n'
                  '# Industry Compatible preset from Blender 4.2.9; generated by tools/generate_ic42.py.\n'
                  + 'DATA = ' + pprint.pformat(data, width=120, sort_dicts=False) + '\n', encoding='utf-8')
